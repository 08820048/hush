#!/bin/bash
# Downloads Apple's password-manager-resources website rules (MIT) and embeds them in HushCore,
# so the app and the CLI work offline and the CLI stays a single file.
# Usage: scripts/update-password-rules.sh
set -euo pipefail
cd "$(dirname "$0")/.."

REPO=apple/password-manager-resources
SHA=$(curl -fsSL "https://api.github.com/repos/$REPO/commits/main" | python3 -c 'import json,sys; print(json.load(sys.stdin)["sha"])')
JSON=$(mktemp)
trap 'rm -f "$JSON"' EXIT
curl -fsSL "https://raw.githubusercontent.com/$REPO/$SHA/quirks/password-rules.json" -o "$JSON"

OUT=Core/Sources/HushCore/PasswordRulesData.swift
python3 - "$SHA" "$OUT" "$JSON" <<'PY'
import json, sys
sha, out, source = sys.argv[1], sys.argv[2], sys.argv[3]
data = json.load(open(source))
rules = {domain: entry["password-rules"] for domain, entry in sorted(data.items()) if "password-rules" in entry}
body = json.dumps(rules, ensure_ascii=False, indent=0, sort_keys=True)
assert '"###' not in body
with open(out, "w") as f:
    f.write("// Generated by scripts/update-password-rules.sh. Do not edit.\n")
    f.write("// Source: https://github.com/apple/password-manager-resources (MIT), quirks/password-rules.json\n")
    f.write(f"// Commit: {sha}\n\n")
    f.write("enum PasswordRulesData {\n")
    f.write(f"    static let sourceCommit = \"{sha}\"\n\n")
    f.write("    /// Domain → password rules string.\n")
    f.write("    static let json = ###\"\"\"\n")
    f.write(body + "\n")
    f.write("\"\"\"###\n}\n")
print(f"{len(rules)} domains from {sha[:7]} → {out}")
PY
